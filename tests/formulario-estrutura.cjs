// NODE_PATH=/tmp/eventos-builder-tests/node_modules node tests/formulario-estrutura.cjs
const {JSDOM} = require('jsdom');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const dom = new JSDOM('<div id="builderRows"></div><div id="builderEmpty"></div><button id="addField"></button>', {runScripts:'outside-only'});
const w = dom.window, d = w.document;
w.eval('window.initial = {campos:[{nome:"turno",label:"Turno",tipo:"select",opcoes:["Manhã"],grid:6},{nome:"outro",label:"Outro",tipo:"text",grid:4}]};');
w.eval(fs.readFileSync('public/js/formulario-estrutura.js','utf8'));
const fields = () => JSON.parse(JSON.stringify(w.readBuilderFields()));
const input = (el, value) => {el.value=value;el.dispatchEvent(new w.Event('input',{bubbles:true}));};
assert.deepEqual(fields()[0].opcoes,[{texto:'Manhã',valor:'Manhã',percentual_vagas:null}]);
d.querySelector('.add-option').click();
let item=d.querySelector('.option-items').lastElementChild;
input(item.querySelector('.option-text'),'São Paulo');
assert.equal(item.querySelector('.option-value').value,'sao_paulo');
input(item.querySelector('.option-text'),'São Paulo Capital');
assert.equal(item.querySelector('.option-value').value,'sao_paulo_capital');
input(item.querySelector('.option-value'),'SP');
input(item.querySelector('.option-text'),'Capital de São Paulo');
assert.equal(fields()[0].opcoes[1].valor,'SP');
item.querySelector('.remove-option').click();
assert.equal(fields()[0].opcoes.length,1);
d.querySelector('.move-down').click();
assert.deepEqual(fields().map(f=>f.nome),['outro','turno']);
d.querySelectorAll('.move-up')[1].click();
assert.equal(fields()[0].nome,'turno');
input(d.querySelector('.f-grid'),'12');
assert(d.querySelector('.field').classList.contains('col-lg-12'));
assert.equal(fields()[0].grid,12);
d.getElementById('addField').click();
input(d.querySelectorAll('.f-label')[2],'Nova pergunta');
assert.equal(fields()[2].nome,'nova_pergunta');
assert.equal(fields()[2].grid,12);
d.querySelectorAll('.remove-field')[2].click();
assert.equal(fields().length,2);
assert(d.querySelector('.move-up').disabled);
assert(d.querySelectorAll('.move-down')[1].disabled);
console.log('OK: opções antigas, sugestão contínua, valor manual, inclusão, remoção, ordem e grid.');
